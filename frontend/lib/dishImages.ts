export function getDishImage(item: { name?: string; image_url?: string | null; category_id?: number }): string {
    const rawName = item.name || "";
    const nameLower = rawName.toLowerCase().trim();

    // 1. Direct exact match in DISH_IMAGE_MAP
    if (nameLower && DISH_IMAGE_MAP[nameLower]) {
        return DISH_IMAGE_MAP[nameLower];
    }

    // 2. Direct match with punctuation stripped
    const stripped = nameLower.replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();
    if (stripped && DISH_IMAGE_MAP[stripped]) {
        return DISH_IMAGE_MAP[stripped];
    }

    // 3. Custom or uploaded valid image from item data
    if (
        item.image_url &&
        item.image_url.startsWith("/dishes/") &&
        !item.image_url.includes("3d_") &&
        !item.image_url.includes("placeholder")
    ) {
        return item.image_url;
    }

    // 4. Substring matching from longest to shortest key in DISH_IMAGE_MAP
    const sortedKeys = Object.keys(DISH_IMAGE_MAP).sort((a, b) => b.length - a.length);
    for (const key of sortedKeys) {
        if (key.length > 3 && (nameLower.includes(key) || key.includes(nameLower))) {
            return DISH_IMAGE_MAP[key];
        }
    }

    // 5. Fallback category image
    return (item.category_id && CATEGORY_DEFAULT_IMAGES[item.category_id]) || "/dishes/cat_biryani.jpg";
}
